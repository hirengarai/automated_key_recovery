#Galois Field Multiplication Macro
def GMUL(a, b, p, d):
	result = 0
	while b > 0:
		if b & 1:
			result ^= a
		a <<= 1
		if a & (1 << d):
			a ^= p
		b >>= 1
	return result & ((1 << d) - 1)



